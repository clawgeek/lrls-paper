# =====================================================================
# Figure 1: architecture / data-flow block diagram
# =====================================================================
def fig_framework(path):
    fig, ax = plt.subplots(figsize=(7.0, 4.6))
    ax.set_xlim(0, 10); ax.set_ylim(0, 6.6); ax.axis("off")

    def box(x, y, w, h, title, lines, fc="#f7f7f4", ec="#444444", title_fs=9):
        ax.add_patch(FancyBboxPatch((x, y), w, h,
                     boxstyle="round,pad=0.06,rounding_size=0.10",
                     linewidth=0.9, edgecolor=ec, facecolor=fc, zorder=2))
        ax.text(x + w/2, y + h - 0.30, title, ha="center", va="top",
                fontsize=title_fs, fontweight="bold", zorder=3)
        for k, ln in enumerate(lines):
            ax.text(x + w/2, y + h - 0.62 - k*0.28, ln, ha="center", va="top",
                    fontsize=7.4, color="#333333", zorder=3)

    def arrow(p, q, style="-|>", ls="-", color="#444444", label=None,
              lx=0, ly=0, fs=7.2, rad=0.0):
        ax.add_patch(FancyArrowPatch(p, q, arrowstyle=style, mutation_scale=11,
                     linewidth=0.9, linestyle=ls, color=color, zorder=1,
                     connectionstyle="arc3,rad=%s" % rad))
        if label:
            mx, my = (p[0]+q[0])/2 + lx, (p[1]+q[1])/2 + ly
            ax.text(mx, my, label, ha="center", va="center", fontsize=fs,
                    color=color, zorder=4,
                    bbox=dict(boxstyle="round,pad=0.15", fc="white", ec="none", alpha=0.9))

    # Scheduler (top)
    box(3.1, 5.3, 3.8, 1.15, "Scheduler  $A_S$",
        ["global state in, budget out: $(N_C, N_B)$",
         "task dispatch, resampling on stall"])
    # Explorer pool (left)
    box(0.25, 2.9, 3.3, 1.7, "Explorer pool  $A_C$  ($\\times 8$)",
        ["coarse sensing, large steps, high entropy",
         "actions: Wander, MarkCave",
         "reward weight: $\\lambda_e \\uparrow$, $\\lambda_v \\downarrow$"])
    # Refiner pool (right)
    box(6.45, 2.9, 3.3, 1.7, "Refiner pool  $A_B$  ($\\times 4$)",
        ["fine sensing, small steps, risk-aware",
         "actions: Migrate, DigLocal, VigilScan, Abandon",
         "reward weight: $\\lambda_v \\uparrow$, $\\lambda_e \\downarrow$"])
    # Memory pool (bottom)
    box(2.5, 0.55, 5.0, 1.35, "Shared memory pool  $M$",
        ["habitat records: mud caves $H_m$ / reef gaps $H_r$",
         "risk map, fitness, trajectory replay partitions"])
    # Environment (bottom-right)
    box(7.6, 0.35, 2.2, 1.0, "Environment",
        ["22$\\times$22 field $f(x,z)$",
         "hard constraints"], fc="#f2f2ef")
    # Task board (bottom-left)
    box(0.25, 0.35, 2.05, 1.0, "Task board",
        ["MAP$\\to$DISCOVER$\\to$VERIFY",
         "$\\to$REFINE$\\to$REPORT"], fc="#f2f2ef")

    # Arrows
    arrow((3.1, 5.35), (1.9, 4.65), label="budget", lx=-0.45, ly=0.0)   # S -> C
    arrow((6.9, 5.35), (8.1, 4.65), label="budget", lx=0.45, ly=0.0)    # S -> B
    arrow((3.55, 3.75), (5.0, 1.95), rad=-0.15,
          label="candidates $H_m$", lx=-0.65, ly=0.15)                  # C -> M
    arrow((6.45, 3.75), (5.0, 1.95), rad=0.15,
          label="verified $H_r$", lx=0.7, ly=0.15)                      # B -> M
    arrow((4.2, 2.9), (6.45, 3.55), rad=-0.2, ls="--",
          label="assignment", ly=0.32)                                   # M -> B (assign)
    arrow((5.0, 0.55), (4.9, 1.6), style="-|>", ls=":", color="#777777") # env->M? skip
    # reward annotation
    ax.text(5.0, 4.55, "$r = r_{obj} - \\lambda_v C_v + \\lambda_e H - \\lambda_m C_m$",
            ha="center", va="center", fontsize=9,
            bbox=dict(boxstyle="round,pad=0.30", fc="white", ec="#999999", lw=0.7))
    # env <-> pools
    arrow((8.1, 1.35), (7.9, 2.9), ls=":", color="#777777",
          label="obs / act", lx=0.55)
    arrow((1.4, 2.9), (1.2, 1.35), ls=":", color="#777777",
          label="obs / act", lx=-0.5)

    fig.subplots_adjust(left=0.01, right=0.99, top=0.99, bottom=0.01)
    fig.savefig(path)
    plt.close(fig)

