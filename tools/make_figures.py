# Figure 3: environment and run footprint (baseline profile P2)
# =====================================================================
def _field_fn(peaks):
    def f(x, z):
        v = 0.0
        for p in peaks:
            d2 = (x - p["x"])**2 + (z - p["z"])**2
            v += p["a"] * np.exp(-d2 / (2 * p["s"]**2))
        v += 0.045 * np.sin(0.85 * x) * np.cos(0.72 * z)
        return np.clip(v, 0, 1)
    return f

def fig_field(path):
    m = next(p["map"] for p in DATA["profiles"] if p["name"] == "P2-default")
    f = _field_fn(m["peaks"])
    xs = np.linspace(-11, 11, 240)
    X, Z = np.meshgrid(xs, xs)
    F = f(X, Z)

    fig, axes = plt.subplots(1, 2, figsize=(7.0, 3.4))

    # (a) objective field + hazards
    a = axes[0]
    cs = a.contourf(X, Z, F, levels=12, cmap="viridis")
    for h in m["hazards"]:
        a.add_patch(Circle((h["x"], h["z"]), h["r"], facecolor="none",
                     edgecolor="#D55E00", hatch="///", lw=0.9, zorder=3))
    for k, pk in enumerate(m["peaks"]):
        opt = k == 0
        a.plot(pk["x"], pk["z"], marker="*" if opt else "o",
               ms=11 if opt else 5, color="#ffffff" if opt else "#f4e3a8",
               mec="#000000", mew=0.6, zorder=4)
    a.set_xlabel("$x$"); a.set_ylabel("$z$")
    a.set_title("(a) objective field $f(x,z)$ with hazard zones", loc="left", fontsize=8.5)
    a.set_xlim(-11, 11); a.set_ylim(-11, 11)
    a.set_aspect("equal")
    cb = fig.colorbar(cs, ax=a, fraction=0.045, pad=0.02)
    cb.set_label("$f$", fontsize=8); cb.ax.tick_params(labelsize=7)
    a.plot([], [], marker="*", ms=9, color="white", mec="k", ls="none",
           label="global optimum")
    a.plot([], [], marker="o", ms=4, color="#f4e3a8", mec="k", ls="none",
           label="sub-optima / decoys")
    hzh = mpatches.Patch(facecolor="none", edgecolor="#D55E00", hatch="///",
                          label="hazard zone ($\\mathrm{risk} > 0$)")
    a.legend(frameon=False, loc="upper left", fontsize=7, handlelength=1.4)

    # (b) run footprint
    a = axes[1]
    tc = np.array([[tr["x"], tr["z"]] for tr in m["trailsC"]])
    tb = np.array([[tr["x"], tr["z"]] for tr in m["trailsB"]])
    a.scatter(tc[:, 0], tc[:, 1], s=1.2, c=OI["sky"], alpha=0.35, lw=0,
              rasterized=True, label="explorer samples")
    a.scatter(tb[:, 0], tb[:, 1], s=1.6, c=OI["verm"], alpha=0.5, lw=0,
              rasterized=True, label="refiner samples")
    for h in m["hazards"]:
        a.add_patch(Circle((h["x"], h["z"]), h["r"], facecolor="none",
                     edgecolor="#D55E00", hatch="///", lw=0.7, zorder=1))
    rp = a.scatter([], [], s=0)
    if m["reefs"]:
        r = np.array([[q["x"], q["z"]] for q in m["reefs"]])
        a.scatter(r[:, 0], r[:, 1], s=30, marker="s", facecolor=OI["green"],
                  edgecolor="k", lw=0.6, zorder=4, label="verified reef gaps")
    cv = [c for c in m["caves"] if c["state"] == "mud"]
    if cv:
        c = np.array([[q["x"], q["z"]] for q in cv])
        a.scatter(c[:, 0], c[:, 1], s=18, marker="^", facecolor="none",
                  edgecolor="#777777", lw=0.7, zorder=3, label="pending mud caves")
    a.plot(m["peaks"][0]["x"], m["peaks"][0]["z"], marker="*", ms=11,
           color="white", mec="k", mew=0.6, zorder=5)
    a.set_xlabel("$x$"); a.set_ylabel("$z$")
    a.set_title("(b) agent footprint, baseline run (t = 1100)", loc="left", fontsize=8.5)
    a.set_xlim(-11, 11); a.set_ylim(-11, 11)
    a.set_aspect("equal")
    a.legend(frameon=False, loc="lower right", fontsize=7, handlelength=1.2,
             handletextpad=0.4)
    a.spines["top"].set_visible(False); a.spines["right"].set_visible(False)

    fig.tight_layout(pad=0.8)
    fig.savefig(path)
    plt.close(fig)

