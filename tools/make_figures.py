# Figure 2: run dynamics across the four operating profiles
# =====================================================================
def fig_dynamics(path):
    fig, axes = plt.subplots(2, 2, figsize=(7.0, 4.8))
    for p in DATA["profiles"]:
        name = p["name"]
        color, ls = next((c, l) for n, c, l in PROFILE_STYLE if n == name)
        t = [row["t"] for row in p["series"]]
        axes[0, 0].plot(t, [row["best"] for row in p["series"]], ls, color=color,
                        lw=1.3, label=PROFILE_LABEL[name])
        axes[0, 1].plot(t, [row["coverage"] for row in p["series"]], ls, color=color,
                        lw=1.3, label=PROFILE_LABEL[name])
        axes[1, 0].plot(t, [row["entropy"] for row in p["series"]], ls, color=color,
                        lw=1.3, label=PROFILE_LABEL[name])
        axes[1, 1].plot(t, [row["vio"] for row in p["series"]], ls, color=color,
                        lw=1.3, label=PROFILE_LABEL[name])

    a = axes[0, 0]
    a.set_xlabel("tick"); a.set_ylabel("best feasible score")
    a.set_ylim(0, 1.04); a.axhline(1.0, color="#999999", lw=0.7, ls=(0, (4, 3)))
    a.text(1020, 1.005, "$f^\\ast$", fontsize=8, color="#666666", ha="right")
    a.set_title("(a)", loc="left", fontweight="bold")

    a = axes[0, 1]
    a.set_xlabel("tick"); a.set_ylabel("map coverage")
    a.set_ylim(0, 1.0); a.set_title("(b)", loc="left", fontweight="bold")

    a = axes[1, 0]
    a.set_xlabel("tick"); a.set_ylabel("normalised entropy $H$")
    a.set_ylim(0, 1.0); a.set_title("(c)", loc="left", fontweight="bold")

    a = axes[1, 1]
    a.set_xlabel("tick"); a.set_ylabel("cumulative violation events")
    a.set_yscale("log"); a.set_title("(d)", loc="left", fontweight="bold")
    a.legend(frameon=False, loc="lower right", handlelength=1.6)

    for a in axes.flat:
        a.set_xlim(0, 1100)
        a.spines["top"].set_visible(False)
        a.spines["right"].set_visible(False)

    fig.tight_layout(pad=0.8)
    fig.savefig(path)
    plt.close(fig)

